import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = resolve(root, "../../docs/api/openapi.json");
const outDir = resolve(root, "src/generated");

const raw = readFileSync(specPath);
const sha256 = createHash("sha256").update(raw).digest("hex");
const spec = JSON.parse(raw.toString("utf8"));

const METHODS = ["get", "put", "post", "delete", "patch", "head", "options"];

const header = (what) =>
  [
    "/**",
    ` * DO NOT EDIT. ${what}`,
    " * Generated by packages/api-client/scripts/generate.mjs from docs/api/openapi.json.",
    ` * openapi-sha256: ${sha256}`,
    " * Run `pnpm -C packages/api-client generate` after the OpenAPI document changes.",
    " */",
    "",
  ].join("\n");

const declares = (operation, location, name) =>
  (operation.parameters ?? []).some(
    (parameter) => parameter.in === location && parameter.name === name,
  );

const declaresInBody = (operation, name) =>
  Object.hasOwn(
    operation.requestBody?.content?.["application/json"]?.schema?.properties ??
      {},
    name,
  );

const withRole = [];
const withBodyRole = [];
const withScope = [];

for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const operation = item[method];
    if (!operation) continue;
    const key = `${method.toUpperCase()} ${path}`;
    if (declares(operation, "query", "role")) withRole.push(key);
    if (declaresInBody(operation, "role")) withBodyRole.push(key);
    if (declares(operation, "query", "scope")) withScope.push(key);
  }
}

const typesSpec = structuredClone(spec);

for (const item of Object.values(typesSpec.paths)) {
  for (const method of METHODS) {
    for (const parameter of item[method]?.parameters ?? []) {
      if (parameter.in === "query" && parameter.name === "role") {
        parameter.required = false;
      }
    }
  }
}

const ast = await openapiTS(typesSpec);
const schema = `${header(
  "Types for the API. The role query parameter is typed optional because the client injects it.",
)}\n${astToString(ast)}`;

const list = (keys) =>
  [...keys]
    .sort()
    .map((key) => `  ${JSON.stringify(key)},`)
    .join("\n");

const meta = `${header("Operation metadata derived from the spec.")}
/** Operations that declare a \`role\` query parameter. Keys are \`METHOD path\`. */
export const operationsWithRole: ReadonlySet<string> = new Set([
${list(withRole)}
]);

/** Operations that declare \`role\` only in the JSON body (the client never touches bodies). */
export const operationsWithBodyRole: ReadonlySet<string> = new Set([
${list(withBodyRole)}
]);

/** Operations that declare a \`scope\` query parameter. */
export const operationsWithScope: ReadonlySet<string> = new Set([
${list(withScope)}
]);
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "schema.ts"), schema);
writeFileSync(resolve(outDir, "meta.ts"), meta);
